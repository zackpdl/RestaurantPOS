#!/usr/bin/env node
/* eslint-disable no-console */

const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');

const argv = process.argv.slice(2);
const argValue = (name, fallback) => {
  const idx = argv.indexOf(name);
  if (idx === -1) return fallback;
  const v = argv[idx + 1];
  if (!v || v.startsWith('--')) return fallback;
  return v;
};
const hasFlag = (name) => argv.includes(name);

const restaurant = argValue('--restaurant', 'Tom Yum Goong');
const dir = argValue('--dir', 'book');
const outSql = argValue('--out-sql', path.join('supabase', 'seed', 'menu_items.sql'));
const outJson = argValue('--out-json', path.join('supabase', 'seed', 'menu_items.json'));
const limit = Number(argValue('--limit', '0')) || 0;
const dryRun = hasFlag('--dry-run');

const ROOT = process.cwd();
const absDir = path.resolve(ROOT, dir);

if (!fs.existsSync(absDir)) {
  console.error(`Directory not found: ${absDir}`);
  process.exit(1);
}

const run = (cmd, args) =>
  execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

const ensureDir = (p) => fs.mkdirSync(p, { recursive: true });
const normalizeSpaces = (s) => s.replace(/\s+/g, ' ').trim();

const preprocess = (inputPath, outputPath) => {
  run('magick', [
    inputPath,
    '-gravity',
    'East',
    '-crop',
    '72%x100%+0+0',
    '+repage',
    '-resize',
    '300%',
    '-colorspace',
    'Gray',
    '-auto-level',
    '-sharpen',
    '0x1',
    outputPath,
  ]);
};

const ocr = (imagePath) => run('tesseract', [imagePath, 'stdout', '-l', 'eng', '--psm', '6']);

const extractPrice = (line) => {
  const nums = line.match(/\d{2,5}/g);
  if (!nums || nums.length === 0) return null;
  // Prefer 3+ digit values at the end of line (typical THB prices).
  const last = nums[nums.length - 1];
  const v = Number(last);
  if (!Number.isFinite(v) || v <= 0) return null;
  return v;
};

const extractId = (line) => {
  const m = line.match(/^\s*(\d{1,3})\s*[.)]\s*/);
  return m ? m[1] : null;
};

const extractName = (line) => {
  // Remove the leading id + dot.
  let s = line.replace(/^\s*\d{1,3}\s*[.)]\s*/, '');
  // Remove trailing price-ish digits and dot leaders.
  s = s.replace(/[.]{2,}/g, ' ');
  s = s.replace(/\d{2,5}\s*$/, '');
  s = normalizeSpaces(s);
  // Keep only the readable English-ish prefix (stop at first non-basic char run).
  s = s.replace(/[^\x20-\x7E]+/g, ' ');
  s = normalizeSpaces(s);
  return s || null;
};

const sqlEscape = (s) => String(s).replace(/'/g, "''");

const images = fs
  .readdirSync(absDir)
  .filter((f) => /\.(jpe?g|png)$/i.test(f))
  .sort((a, b) => {
    const na = Number(path.parse(a).name);
    const nb = Number(path.parse(b).name);
    if (Number.isFinite(na) && Number.isFinite(nb)) return na - nb;
    return a.localeCompare(b);
  });

const take = limit > 0 ? images.slice(0, limit) : images;
if (take.length === 0) {
  console.error(`No images found in: ${absDir}`);
  process.exit(1);
}

const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pos-menu-simple-'));
const items = [];
const seen = new Set();

console.log(`OCR (simple) ${take.length} image(s) from ${dir} -> ${restaurant}`);

for (const file of take) {
  const inputPath = path.join(absDir, file);
  const prePath = path.join(tmpDir, `${path.parse(file).name}.png`);
  try {
    preprocess(inputPath, prePath);
    const text = ocr(prePath);
    const lines = text.split(/\r?\n/);
    for (const raw of lines) {
      const line = normalizeSpaces(raw);
      if (!line) continue;
      const id = extractId(line);
      if (!id) continue;
      const price = extractPrice(line);
      const name = extractName(line);
      if (!price || !name) continue;
      const key = `${restaurant}:${id}`;
      if (seen.has(key)) continue;
      seen.add(key);
      items.push({
        restaurant,
        id,
        name,
        price,
        category: 'main',
        source: file,
        ocr: line,
      });
    }
  } catch (e) {
    console.warn(`Failed OCR for ${file}: ${e?.message || e}`);
  }
}

items.sort((a, b) => Number(a.id) - Number(b.id));
console.log(`Parsed ${items.length} item(s).`);

ensureDir(path.dirname(path.resolve(ROOT, outSql)));

const sqlLines = [];
sqlLines.push('-- Generated by scripts/ocr-menu-simple.js');
sqlLines.push(`-- Restaurant: ${restaurant}`);
sqlLines.push('');
sqlLines.push('insert into menu_items (restaurant, id, name, price, category)');
sqlLines.push('values');
items.forEach((item, idx) => {
  sqlLines.push(
    `  ('${sqlEscape(item.restaurant)}', '${sqlEscape(item.id)}', '${sqlEscape(item.name)}', ${item.price}, '${sqlEscape(item.category)}')` +
      (idx === items.length - 1 ? '' : ',')
  );
});
sqlLines.push('on conflict (restaurant, id) do update set');
sqlLines.push('  name = excluded.name,');
sqlLines.push('  price = excluded.price,');
sqlLines.push('  category = excluded.category;');
sqlLines.push('');

if (dryRun) {
  console.log(sqlLines.slice(0, 40).join('\n'));
  console.log('---');
  console.log(`Dry run: not writing ${outSql} / ${outJson}`);
  process.exit(0);
}

fs.writeFileSync(path.resolve(ROOT, outSql), sqlLines.join('\n'), 'utf8');
fs.writeFileSync(path.resolve(ROOT, outJson), JSON.stringify(items, null, 2), 'utf8');
console.log(`Wrote ${outSql}`);
console.log(`Wrote ${outJson}`);

